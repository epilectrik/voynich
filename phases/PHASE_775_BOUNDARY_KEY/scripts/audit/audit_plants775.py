"""PHASE_775 lock audit (lean-expert): no-message plants with WITHIN-FOLIO non-stationarity, and keyed ciphers whose
hidden stream has line- or paragraph-level clustering but no word order. Controls only: B's real token lines are
never scored (B supplies its skeleton and the adjacent-pair tables of habit3, the phase's declared exposure).

Question: can a process with no keyed message, or a keyed process with no word order, reach the PRESENT bar
(G_K >= tau_K) when its structure varies within a folio at the line or paragraph level? The header-aware EF null
permutes within folio x line type, so any line- or paragraph-level clustering is destroyed by the null and enters dS.

Plants (all in B's skeleton):
  TEMP-u   habit3 with sampling probabilities ~ count^beta; beta drawn per unit u (line or paragraph) from {lo, hi}
  SECMIX-u habit3 fitted per section; each unit u is generated by the chain of a section drawn at random
           (weights = B's line counts per section), so lines of one folio come from different chains
  EDIAL-u  habit3 output, then a per-unit e-dial: mode 1 lengthens one e-run (if the longer form exists in B's
           vocabulary), mode 0 shortens one (if the shorter form exists), each with probability q
  KTWIN-u  context-keyed cipher (true key K1 or K2) of a plaintext segment whose words are shuffled within each unit u
           (line or paragraph): unit composition kept, word order destroyed
  KEY      the ordinary keyed cipher of the same segment (reference)

Every corpus is scored with the phase's own pipeline (key775.Decoder, ef774.Corpus with the phase's EF groups and the
same RNG use as key775.run, so the lag-1 numbers equal key775.run's), plus a lag-2 version of S on the same samples.

Usage: python audit_plants775.py [workers<=4]
"""
